"""Convert Terminal-Bench 2 (Harbor format) tasks into aethens-task/v1 tasks.

Usage:
  python bench/tbench/convert_tb2.py --tb2 DIR --out DIR [--only a,b,c] [--docker "sg docker -c"]

DIR for --tb2 is a checkout of github.com/harbor-framework/terminal-bench-2 at the commit pinned in
bench/tbench/README.md (fetch it with bench/tbench/fetch_tb2.sh). Nothing from Terminal-Bench is
committed to this repository: its task files carry a "never in training corpora" canary.

The Aethens sandbox is NOT changed (no root, no network, read-only root filesystem, the work
directory bind-mounted at /work). Instead, every network or root step that Harbor performs at test
time is moved to image-build or data-preparation time, outside the sandbox:

  image     a derived image built FROM the task's own image (pinned by digest) that adds
            (a) uv 0.9.5 and a Python 3.13 venv at /opt/aethens/venv with exactly the `-w` packages
                that the task's tests/test.sh passes to `uvx -p 3.13` (same pins), and
            (b) /app -> /work and /tests -> /work/tests symlinks, so the task's absolute paths
                resolve inside Aethens' disposable work directory.
  starter   the contents of /app in the task's original image.
  gold      the files under /app that the task's own solution/solve.sh created or changed, run once
            as root with network in a throwaway container (the "oracle" run, like Harbor's oracle
            agent). Right after that the task's ORIGINAL tests/test.sh is run in the same container
            and its reward is recorded as `oracle_reward`, so an adaptation problem can be told
            apart from a verifier problem.
  tests     the task's tests/ directory, verbatim.
  verifier  [/usr/bin/env -C <image WORKDIR> when it is not /app]
            /opt/aethens/venv/bin/python -m pytest -p no:cacheprovider <the task's own pytest
            arguments minus --ctrf>. `-p no:cacheprovider` only stops pytest writing a cache dir.

Only tasks whose tests/test.sh is the standard Harbor template (apt-get curl, install uv, one `uvx
-p 3.13 -w ... pytest ... /tests/test_outputs.py` call, write reward.txt) are converted. Anything
else is skipped with a reason in DIR/conversion.json. Known differences from Harbor, recorded per
task: files that solve.sh DELETES under /app cannot be expressed as an overlay; state solve.sh
leaves outside /app (installed packages, services) is not carried over; the sandbox's limits
(Aethens defaults: 1 CPU, 1024 MiB) can be lower than the task's.
"""

from __future__ import annotations

import argparse
import hashlib
import io
import json
import re
import shlex
import shutil
import subprocess
import sys
import tarfile
import tempfile
import tomllib
from pathlib import Path
from typing import Any

UV_IMAGE = "ghcr.io/astral-sh/uv:0.9.5"
VENV = "/opt/aethens/venv"
MAX_FILE_BYTES = 5 * 1024 * 1024  # aethens-task/v1 per-file limit

# Lines of the standard Harbor test.sh template that do not affect what is tested.
_BOILERPLATE = [
    r"#.*",
    r"apt-get update",
    r"apt-get install -y curl",
    r"curl -LsSf https://astral\.sh/uv/[0-9.]+/install\.sh \| sh",
    r"source \$HOME/\.local/bin/env",
    r'if \[ "\$PWD" = "/" \]; then',
    r'echo "Error: No working directory set\..*"',
    r"exit 1",
    r"fi",
    r"if \[ \$\? -eq 0 \]; then",
    r"echo [01] > /logs/verifier/reward\.txt",
    r"else",
]
_BOILER_RE = re.compile("^(?:" + "|".join(_BOILERPLATE) + ")$")

DOCKERFILE = """# Generated by bench/tbench/convert_tb2.py for {name}
FROM {base}
USER root
COPY --from={uv_image} /uv /usr/local/bin/uv
ENV UV_PYTHON_INSTALL_DIR=/opt/aethens/python
RUN UV_CACHE_DIR=/tmp/aethens-uv uv venv -p 3.13 {venv} \\
 && UV_CACHE_DIR=/tmp/aethens-uv uv pip install -p {venv}/bin/python {deps} \\
 && rm -rf /tmp/aethens-uv && chmod -R a+rX /opt/aethens
RUN rm -rf /app /tests && ln -s /work /app && ln -s /work/tests /tests
# uvx runs pytest with its environment's bin/ first on PATH (tests may call `python3`).
ENV PATH={venv}/bin:$PATH
"""

TASK_YAML = """schema: aethens-task/v1
id: {id}
language: python
image: {image}
statement: statement.md
starter: starter
tests: tests
verifier: {verifier}
timeout_s: {timeout}
gold: gold
"""


class Skip(Exception):
    pass


def parse_test_sh(text: str) -> tuple[list[str], list[str]]:
    """Return (pip requirements, pytest args) of a standard Harbor test.sh, else raise Skip."""
    joined = re.sub(r"\\\n", " ", text)
    deps: list[str] = []
    pytest_args: list[str] | None = None
    for raw in joined.splitlines():
        line = raw.strip()
        if not line or _BOILER_RE.match(line):
            continue
        if line.startswith("uvx "):
            if pytest_args is not None:
                raise Skip("more than one uvx call")
            words = shlex.split(line)
            i = 1
            py = None
            while i < len(words) and words[i] != "pytest":
                if words[i] == "-p":
                    py = words[i + 1]
                    i += 2
                elif words[i] == "-w":
                    deps.append(words[i + 1])
                    i += 2
                else:
                    raise Skip(f"unknown uvx option {words[i]!r}")
            if py != "3.13":
                raise Skip(f"uvx python {py!r}, expected 3.13")
            if i >= len(words):
                raise Skip("uvx does not run pytest")
            rest = words[i + 1 :]
            args: list[str] = []
            j = 0
            while j < len(rest):
                if rest[j] == "--ctrf":
                    j += 2
                    continue
                args.append(rest[j])
                j += 1
            pytest_args = args
            continue
        raise Skip(f"non-template test.sh line: {line[:80]!r}")
    if pytest_args is None:
        raise Skip("no uvx pytest call")
    return deps, pytest_args


class Docker:
    def __init__(self, prefix: list[str]) -> None:
        self.prefix = prefix

    def run(
        self,
        args: list[str],
        *,
        input_bytes: bytes | None = None,
        check: bool = True,
        timeout: float | None = None,
    ) -> subprocess.CompletedProcess[bytes]:
        # `sg docker -c` takes one command string; quote each argument. No shell=True here.
        cmd = [*self.prefix, shlex.join(["docker", *args])] if self.prefix else ["docker", *args]
        proc = subprocess.run(  # noqa: S603 - fixed docker argv built by this script
            cmd, input=input_bytes, capture_output=True, timeout=timeout, check=False
        )
        if check and proc.returncode != 0:
            raise RuntimeError(
                f"docker {args[:3]} failed: {proc.stderr.decode(errors='replace')[-800:]}"
            )
        return proc


def _is_within(path: Path, root: Path) -> bool:
    """Return True if *path* is *root* or a descendant of *root*."""
    try:
        path.relative_to(root)
        return True
    except ValueError:
        return False


def _dest_for_app_member(name: str, dest: Path) -> Path | None:
    """Map a docker-cp /app tar member name to a path under dest.

    Strips the leading ``app/``. Returns None for the ``app`` directory itself
    and for members not under ``app/``. Raises Skip for absolute paths, ``..``
    components, or a resolved path that would land outside dest.
    """
    raw = name.replace("\\", "/")
    if raw.startswith("/") or (len(raw) >= 2 and raw[1] == ":"):
        raise Skip(f"tar member has an absolute path: {name}")
    raw_parts = [p for p in raw.split("/") if p and p != "."]
    if ".." in raw_parts:
        raise Skip(f"tar member escapes destination: {name}")
    parts = Path(*raw_parts).parts if raw_parts else ()
    if not parts or parts[0] != "app":
        return None
    if len(parts) == 1:
        return None
    rel = Path(*parts[1:])
    if rel.is_absolute():
        raise Skip(f"tar member has an absolute path: {name}")
    root = dest.resolve()
    target = root / rel
    if not _is_within(target.resolve(), root):
        raise Skip(f"tar member escapes destination: {name}")
    return target


def _extract_app(tar_bytes: bytes, dest: Path) -> None:
    """Extract a `docker cp c:/app -` tar into dest (the leading `app/` is stripped).

    Members with absolute paths, ``..`` components, or a resolved destination
    outside dest are rejected, as are symlinks, hardlinks, and special files.
    """
    dest = dest.resolve()
    dest.mkdir(parents=True, exist_ok=True)
    with tarfile.open(fileobj=io.BytesIO(tar_bytes)) as tf:
        for m in tf.getmembers():
            target = _dest_for_app_member(m.name, dest)
            if target is None:
                continue
            if m.issym() or m.islnk():
                raise Skip(f"/app contains a link: {m.name}")
            if m.isdir():
                target.mkdir(parents=True, exist_ok=True)
            elif m.isfile():
                target.parent.mkdir(parents=True, exist_ok=True)
                f = tf.extractfile(m)
                assert f is not None
                target.write_bytes(f.read())
                target.chmod(m.mode & 0o777)  # keep modes: tests can check them
            else:
                raise Skip(f"/app contains a special file: {m.name}")


def _files(root: Path) -> dict[str, str]:
    out = {}
    for p in sorted(root.rglob("*")):
        if p.is_file():
            out[p.relative_to(root).as_posix()] = hashlib.sha256(p.read_bytes()).hexdigest()
    return out


def convert(task_dir: Path, out: Path, docker: Docker) -> dict[str, Any]:
    name = task_dir.name
    meta = tomllib.loads((task_dir / "task.toml").read_text(encoding="utf-8"))
    env = meta.get("environment", {})
    deps, pytest_args = parse_test_sh((task_dir / "tests" / "test.sh").read_text(encoding="utf-8"))
    image = str(env["docker_image"])
    if int(env.get("gpus", 0) or 0):
        raise Skip("needs a GPU")
    docker.run(["image", "inspect", image])  # must be pulled already (fails loudly otherwise)
    digest = (
        docker.run(["image", "inspect", "--format", "{{index .RepoDigests 0}}", image])
        .stdout.decode()
        .strip()
    )

    workdir = (
        docker.run(["image", "inspect", "--format", "{{.Config.WorkingDir}}", digest])
        .stdout.decode()
        .strip()
        or "/"
    )
    if workdir != "/app" and not workdir.startswith("/app/"):
        raise Skip(f"image WORKDIR {workdir!r} is outside /app")

    dest = out / "tasks" / f"tb2-{name}"
    if dest.exists():
        shutil.rmtree(dest)
    starter, gold = dest / "starter", dest / "gold"

    # Starter: /app of the untouched image.
    cid = docker.run(["create", digest]).stdout.decode().strip()
    try:
        tar = docker.run(["cp", f"{cid}:/app", "-"], check=False)
        if tar.returncode != 0:
            raise Skip("image has no /app")
        _extract_app(tar.stdout, starter)
    finally:
        docker.run(["rm", "-f", cid], check=False)

    # Oracle run: solve.sh as root with network, snapshot /app, then the ORIGINAL test.sh.
    cname = f"aethens-tb2-oracle-{name}"
    docker.run(["rm", "-f", cname], check=False)
    docker.run(["run", "-d", "--name", cname, "--entrypoint", "sleep", digest, "infinity"])
    record: dict[str, Any] = {
        "task": name,
        "base_image": digest,
        "test_deps": deps,
        "pytest_args": pytest_args,
    }
    try:
        for sub in ("solution", "tests"):
            docker.run(["cp", str(task_dir / sub), f"{cname}:/{sub}"])
        solve = docker.run(
            ["exec", "-w", workdir, cname, "bash", "/solution/solve.sh"], check=False, timeout=3600
        )
        record["solve_exit"] = solve.returncode
        if solve.returncode != 0:
            raise Skip(
                f"solve.sh exited {solve.returncode}: "
                f"{solve.stderr.decode(errors='replace')[-300:]}"
            )
        solved = Path(tempfile.mkdtemp(prefix="tb2-solved-"))
        try:
            _extract_app(docker.run(["cp", f"{cname}:/app", "-"]).stdout, solved)
            before, after = _files(starter), _files(solved)
            changed = [p for p, h in after.items() if before.get(p) != h]
            record["gold_files"] = changed
            record["deleted_by_solve"] = sorted(set(before) - set(after))
            for rel in changed:
                (gold / rel).parent.mkdir(parents=True, exist_ok=True)
                shutil.copy2(solved / rel, gold / rel)
            gold.mkdir(parents=True, exist_ok=True)
        finally:
            shutil.rmtree(solved, ignore_errors=True)
        docker.run(["exec", cname, "mkdir", "-p", "/logs/verifier"])
        t = docker.run(
            ["exec", "-w", workdir, cname, "bash", "/tests/test.sh"], check=False, timeout=3600
        )
        rew = docker.run(["exec", cname, "cat", "/logs/verifier/reward.txt"], check=False)
        record["oracle_reward"] = rew.stdout.decode().strip() or None
        record["oracle_test_exit"] = t.returncode
    finally:
        docker.run(["rm", "-f", cname], check=False)

    # Derived image.
    tag = (
        f"aethens-tb2/{name}:{hashlib.sha256((digest + ' '.join(deps)).encode()).hexdigest()[:12]}"
    )
    dockerfile = DOCKERFILE.format(
        name=name,
        base=digest,
        uv_image=UV_IMAGE,
        venv=VENV,
        deps=" ".join(shlex.quote(d) for d in deps),
    )
    (dest / "aethens-image").mkdir(parents=True, exist_ok=True)
    (dest / "aethens-image" / "Dockerfile").write_text(dockerfile, encoding="utf-8")
    docker.run(["build", "-q", "-t", tag, "-"], input_bytes=dockerfile.encode(), timeout=3600)
    record["image"] = tag

    shutil.copytree(task_dir / "tests", dest / "tests")
    big = [p for p in dest.rglob("*") if p.is_file() and p.stat().st_size > MAX_FILE_BYTES]
    if big:  # aethens-task/v1 rejects files over 5 MiB (OversizedFileError)
        shutil.rmtree(dest)
        raise Skip(f"file over 5 MiB: {big[0].relative_to(dest)}")
    shutil.copy2(task_dir / "instruction.md", dest / "statement.md")
    # Harbor runs test.sh in the image's WORKDIR; keep that cwd (Aethens starts in /work = /app).
    prefix = [] if workdir == "/app" else ["/usr/bin/env", "-C", workdir]
    record["workdir"] = workdir
    verifier = [
        *prefix,
        f"{VENV}/bin/python",
        "-m",
        "pytest",
        "-p",
        "no:cacheprovider",
        *pytest_args,
    ]
    timeout = int(min(float(meta.get("verifier", {}).get("timeout_sec", 900)), 3600))
    (dest / "task.yaml").write_text(
        TASK_YAML.format(
            id=f"tb2-{name}", image=tag, verifier=json.dumps(verifier), timeout=timeout
        ),
        encoding="utf-8",
    )
    record["task_limits"] = {"cpus": env.get("cpus"), "memory_mb": env.get("memory_mb")}
    return record


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--tb2", required=True, type=Path)
    ap.add_argument("--out", required=True, type=Path)
    ap.add_argument("--only", default="", help="comma-separated task names")
    ap.add_argument("--docker", default="", help='prefix, e.g. "sg docker -c"')
    a = ap.parse_args(argv)
    docker = Docker(shlex.split(a.docker))
    names = [n for n in a.only.split(",") if n] or sorted(
        p.name for p in a.tb2.iterdir() if (p / "task.toml").is_file()
    )
    a.out.mkdir(parents=True, exist_ok=True)
    log_path = a.out / "conversion.json"
    log: dict[str, Any] = json.loads(log_path.read_text()) if log_path.exists() else {}
    for n in names:
        try:
            log[n] = {"status": "converted", **convert(a.tb2 / n, a.out, docker)}
        except Skip as exc:
            log[n] = {"status": "skipped", "reason": str(exc)}
        except Exception as exc:  # recorded, not hidden: the run continues with the next task
            log[n] = {"status": "error", "reason": f"{type(exc).__name__}: {exc}"}
        print(
            n, log[n]["status"], log[n].get("reason", log[n].get("oracle_reward", "")), flush=True
        )
        log_path.write_text(json.dumps(log, indent=1, sort_keys=True) + "\n", encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
